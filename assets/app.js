  function libraryFiltered() {
    const f = ui.library;
    const terms = normText(f.q).split(' ').filter(Boolean);
    let list = questions.filter((q) => {
      if (f.domain && q._domain !== f.domain) return false;
      if (f.objective && q._objective !== f.objective) return false;
      if (f.pack && q.pack !== f.pack) return false;
      if (f.type && q.type !== f.type) return false;
      if (f.status && q.answerStatus !== f.status) return false;
      if (f.flag && !(q.flags || []).includes(f.flag)) return false;
      if (f.difficulty && String(q.difficulty) !== String(f.difficulty)) return false;
      if (f.attempt === 'unseen' && isAttempted(q.id)) return false;
      if (f.attempt === 'seen' && !isAttempted(q.id)) return false;
      if (f.attempt === 'wrong' && lastResultOf(q.id) !== 'wrong') return false;
      if (f.attempt === 'bookmarked' && !isBookmarked(q.id)) return false;
      if (f.attempt === 'flagged' && !isFlagged(q.id)) return false;
      if (terms.length) {
        const hay = searchText(q);
        if (!terms.every((t) => hay.includes(t))) return false;
      }
      return true;
    });
    if (f.sort === 'id') list.sort((a, b) => a.id.localeCompare(b.id));
    else if (f.sort === 'difficulty') list.sort((a, b) => (b.difficulty || 0) - (a.difficulty || 0) || a.id.localeCompare(b.id));
    else if (f.sort === 'weakest') list.sort((a, b) => {
      const aa = attemptOf(a.id); const bb = attemptOf(b.id);
      const aw = aa && aa.lastResult === 'wrong' ? 0 : aa ? 1 : 2;
      const bw = bb && bb.lastResult === 'wrong' ? 0 : bb ? 1 : 2;
      return aw - bw || a.id.localeCompare(b.id);
    });
    else if (terms.length) {
      list.sort((a, b) => libraryScore(b, terms) - libraryScore(a, terms) || a.id.localeCompare(b.id));
    } else {
      list.sort((a, b) => OBJECTIVE_ORDER.indexOf(a._objective) - OBJECTIVE_ORDER.indexOf(b._objective) || a.id.localeCompare(b.id));
    }
    return list;
  }

  function libraryScore(q, terms) {
    const stem = normText(q.stem);
    let score = 0;
    for (const t of terms) {
      if (stem.startsWith(t)) score += 8;
      else if (stem.includes(t)) score += 5;
      if (normText(q.id).includes(t)) score += 4;
      if ((q.options || []).some((o) => normText(o.text).includes(t))) score += 3;
      if (normText(q.explanation).includes(t)) score += 1;
    }
    return score;
  }

