  function aggregate(qs) {
    let attempted = 0;
    let correct = 0;
    let wrong = 0;
    let disputed = 0;
    let ungraded = 0;
    for (const q of qs) {
      const a = attemptOf(q.id);
      if (!a || !a.seen) continue;
      attempted++;
      correct += a.correct || 0;
      wrong += a.wrong || 0;
      disputed += a.disputed || 0;
      ungraded += a.ungraded || 0;
    }
    const graded = correct + wrong;
    const accuracy = graded ? correct / graded : null;
    const coverage = qs.length ? attempted / qs.length : 0;
    // Shrink accuracy toward 50% until there is evidence, then blend with coverage.
    const shrunk = graded ? (correct + 2) / (graded + 4) : null;
    const mastery = graded
      ? Math.round(100 * (0.72 * shrunk + 0.28 * Math.min(1, coverage / 0.8)))
      : null;
    return { total: qs.length, attempted, correct, wrong, disputed, ungraded, graded, accuracy, coverage, mastery };
  }

