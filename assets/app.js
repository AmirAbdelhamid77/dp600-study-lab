  function doSubmitExam(auto) {
    const s = state.examSession;
    if (!s || s._submitting) return;
    s._submitting = true;
    const items = s.ids.map((qid) => {
      const q = byId.get(qid);
      const response = s.responses[qid] || null;
      const answered = responseComplete(q, response);
      const grade = answered
        ? gradeResponse(q, response)
        : q.answerStatus === 'conflict'
          ? { status: 'disputed', correct: null }
          : q.answerStatus === 'missing'
            ? { status: 'ungraded', correct: null }
            : { status: 'wrong', correct: false };
      return { qid, response, answered, status: grade.status, correct: grade.correct, flagged: Boolean(s.flags[qid]) };
    });
    const gradedItems = items.filter((i) => i.status === 'correct' || i.status === 'wrong');
    const correct = items.filter((i) => i.status === 'correct').length;
    const wrong = items.filter((i) => i.status === 'wrong').length;
    const answeredWrong = items.filter((i) => i.answered && i.status === 'wrong').length;
    const unanswered = items.filter((i) => !i.answered).length;
    const flagged = items.filter((i) => i.flagged).length;
    const score = gradedItems.length ? correct / gradedItems.length : 0;
    const byDomain = {};
    for (const d of DOMAIN_ORDER) {
      const subset = items.filter((i) => byId.get(i.qid)._domain === d);
      if (!subset.length) continue;
      const c = subset.filter((i) => i.status === 'correct').length;
      const w = subset.filter((i) => i.status === 'wrong').length;
      byDomain[d] = { total: subset.length, correct: c, wrong: w, score: c + w ? c / (c + w) : null };
    }
    const durationSec = clamp(Math.round((Date.now() - s.startedAt) / 1000), 0, s.durationSec);
    const result = {
      id: s.id,
      at: Date.now(),
      startedAt: s.startedAt,
      durationSec,
      count: items.length,
      graded: gradedItems.length,
      correct,
      wrong,
      answeredWrong,
      unanswered,
      flagged,
      score,
      byDomain,
      items,
      config: s.config,
    };
    for (const item of items) {
      const q = byId.get(item.qid);
      if (!q) continue;
      if (item.status === 'correct' || item.status === 'wrong') recordAttempt(q, item.response, item.status, 'exam');
      else if (item.status === 'disputed') recordAttempt(q, item.response, 'disputed', 'exam');
      else if (item.status === 'ungraded') recordAttempt(q, item.response, 'ungraded', 'exam');
      else recordAttempt(q, item.response, 'wrong', 'exam');
    }
    state.exams.unshift(result);
    state.exams = state.exams.slice(0, 20);
    state.lastExam = result;
    state.examSession = null;
    ui.examResultsOpen = true;
    ui.examReviewId = result.id;
    ui.examReviewIndex = 0;
    saveStateNow();
    render();
    toast(auto ? 'Time is up — exam submitted.' : 'Exam submitted.', auto ? 'warn' : 'success', 5000);
  }

