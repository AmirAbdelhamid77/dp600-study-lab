  function renderControls(q, opts) {
    const { interactive, revealed, response, reviewMode } = opts;
    const controls = q.controls || (q.answer && q.answer.controls) || [];
    if (!controls.length) return '';
    const actual = (response && response.controls) || [];
    const expected = (q.answer && q.answer.controls) || [];
    return `<div class="controls">${controls.map((c, i) => {
      const value = actual[i] || '';
      const correctValue = expected[i] ? expected[i].answer : '';
      const isCorrect = revealed || reviewMode ? normalizeAnswerText(value) === normalizeAnswerText(correctValue) : null;
      const cls = revealed || reviewMode ? (isCorrect ? 'is-correct' : value ? 'is-incorrect' : '') : '';
      return `<div class="control-row ${cls}">
        <div class="control-label">${esc(c.label)}</div>
        <select class="select control-select" data-action="select-control" data-index="${i}" ${interactive ? '' : 'disabled'} aria-label="${attr(c.label)}">
          <option value="">Select…</option>
          ${(c.options || []).map((opt) => `<option value="${attr(opt)}" ${value === opt ? 'selected' : ''}>${esc(opt)}</option>`).join('')}
        </select>
        ${revealed || reviewMode ? `<div class="small ${isCorrect ? '' : 'muted'}" style="grid-column:1/-1">${isCorrect ? `${icon('check', 'icon icon-sm')} Correct` : `Key: <strong>${esc(correctValue)}</strong>`}</div>` : ''}
      </div>`;
    }).join('')}</div>`;
  }

  function renderSequence(q, opts) {
    const { interactive, revealed, response, reviewMode } = opts;
    const order = (response && response.order && response.order.length === (q.options || []).length)
      ? response.order
      : (q.options || []).map((o) => o.key);
    const correct = (q.answer && q.answer.order) || [];
    return `<div class="sequence-list" role="list" aria-label="Ordered steps">${order.map((key, i) => {
      const text = optionText(q, key);
      const isCorrect = revealed || reviewMode ? correct[i] === key : null;
      const cls = revealed || reviewMode ? (isCorrect ? 'is-correct' : 'is-incorrect') : '';
      return `<div class="sequence-item ${cls}" role="listitem">
        <span class="sequence-num">${i + 1}</span>
        <span class="sequence-text"><strong>${esc(key)}.</strong> ${esc(text)}</span>
        ${interactive ? `<span class="sequence-actions">
          <button class="seq-btn" type="button" data-action="sequence-move" data-index="${i}" data-dir="-1" ${i === 0 ? 'disabled' : ''} aria-label="Move up">${icon('chevron-left', 'icon icon-sm')}</button>
          <button class="seq-btn" type="button" data-action="sequence-move" data-index="${i}" data-dir="1" ${i === order.length - 1 ? 'disabled' : ''} aria-label="Move down">${icon('chevron-right', 'icon icon-sm')}</button>
        </span>` : ''}
      </div>`;
    }).join('')}</div>${(revealed || reviewMode) && correct.length ? `<div class="callout info" style="margin-top:12px">${icon('info')}<div><strong>Correct order:</strong> ${esc(correct.join(' → '))}</div></div>` : ''}`;
  }

  function renderAnswerPanel(q, response, result) {
    if (!q.answer && q.answerStatus !== 'missing') return '';
    const correctText = q.answer ? answerText(q, q.answer) : 'No answer key was supplied.';
    const responseTextValue = response ? responseText(q, response) : 'No response recorded.';
    if (q.answerStatus === 'conflict') {
      return `<div class="callout warn" style="margin-top:12px">${icon('alert')}<div><strong>Sources disagree on this answer.</strong> The key shown is the most common variant. Compare both keys before you rely on it.<div class="small" style="margin-top:6px"><strong>Shown key:</strong><br>${esc(correctText)}</div>${(q.conflictVariants || []).map((v) => `<div class="small" style="margin-top:8px"><strong>Variant ${esc(v.answer)}:</strong><br>${esc(answerText(q, v.answerData || null))}<br><span class="faint">${v.sources.map((s) => esc(s.locator)).join(', ')}</span></div>`).join('')}</div></div>`;
    }
    if (q.answerStatus === 'missing') {
      return `<div class="callout warn" style="margin-top:12px">${icon('alert')}<div><strong>Study-only item.</strong> No answer key was supplied, so this question is not scored. Use the explanation and references to reason about it.</div></div>`;
    }
    return `<div class="answer-line"><span>Correct answer</span><strong>${esc(correctText)}</strong></div>${result === 'wrong' ? `<div class="answer-line"><span>Your answer</span><strong>${esc(responseTextValue)}</strong></div>` : ''}`;
  }

  function renderFeedback(q, response, result) {
    const status = result || (q.answerStatus === 'missing' ? 'ungraded' : q.answerStatus === 'conflict' ? 'disputed' : null);
    if (!status) return '';
    const kind = status === 'correct' ? 'correct' : status === 'wrong' ? 'incorrect' : status === 'disputed' ? 'disputed' : status === 'ungraded' ? 'ungraded' : 'revealed';
    const head = status === 'correct' ? `${icon('check-circle')} Correct`
      : status === 'wrong' ? `${icon('x-circle')} Not quite`
      : status === 'disputed' ? `${icon('alert')} Disputed key`
      : status === 'ungraded' ? `${icon('info')} Study only — not scored`
      : `${icon('eye')} Answer &amp; explanation`;
    const explanation = q.explanation ? `<p class="explanation">${esc(q.explanation)}</p>` : `<p class="muted">No explanation was supplied with this item.</p>`;
    const why = (q.options || []).filter((o) => o.why).length
      ? `<div class="why-list">${(q.options || []).filter((o) => o.why).map((o) => {
        const isKey = q.answer && q.answer.letters && q.answer.letters.includes(o.key);
        return `<div class="why-item ${isKey ? 'is-correct' : ''}"><span class="why-key">${esc(o.key)}</span><span>${esc(o.why)}</span></div>`;
      }).join('')}</div>`
      : '';
    return `<div class="feedback ${kind}" role="status">
      <div class="feedback-head">${head}</div>
      <div class="feedback-body">
        ${renderAnswerPanel(q, response, status)}
        ${explanation}
        ${why}
        ${renderProvenance(q)}
      </div>
    </div>`;
  }

