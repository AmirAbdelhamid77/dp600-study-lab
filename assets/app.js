  function reviewQueue(tab) {
    let list;
    if (tab === 'bookmarked') list = Object.keys(state.bookmarks).map((id) => byId.get(id)).filter(Boolean);
    else if (tab === 'unseen') list = questions.filter((q) => !isAttempted(q.id));
    else if (tab === 'conflicts') list = questions.filter((q) => q.answerStatus === 'conflict');
    else if (tab === 'uncertain') list = uncertainQuestions();
    else if (tab === 'flagged') list = Object.keys(state.flags).map((id) => byId.get(id)).filter(Boolean);
    else list = needsWorkQuestions();

    const q = normText(ui.review.q);
    if (q) list = list.filter((item) => searchText(item).includes(q));
    if (ui.review.domain) list = list.filter((item) => item._domain === ui.review.domain);

    if (tab === 'needsWork') {
      list.sort((a, b) => (attemptOf(b.id)?.lastAt || 0) - (attemptOf(a.id)?.lastAt || 0));
    } else if (tab === 'bookmarked') {
      list.sort((a, b) => (state.bookmarks[b.id] || 0) - (state.bookmarks[a.id] || 0));
    } else {
      list.sort((a, b) => OBJECTIVE_ORDER.indexOf(a._objective) - OBJECTIVE_ORDER.indexOf(b._objective) || a.id.localeCompare(b.id));
    }
    return list;
  }

