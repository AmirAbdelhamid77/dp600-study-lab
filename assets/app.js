  function applyImportedState(data) {
    const src = data && data.state ? data.state : data;
    if (!src || typeof src !== 'object' || Array.isArray(src)) throw new Error('The file is not a progress backup.');
    if (!src.attempts && !src.exams && !src.bookmarks) throw new Error('No progress data was found in the file.');
    state.settings = { ...DEFAULT_STATE.settings, ...(src.settings || {}) };
    state.attempts = src.attempts && typeof src.attempts === 'object' ? src.attempts : {};
    state.bookmarks = src.bookmarks && typeof src.bookmarks === 'object' ? src.bookmarks : {};
    state.flags = src.flags && typeof src.flags === 'object' ? src.flags : {};
    state.activity = src.activity && typeof src.activity === 'object' ? src.activity : {};
    state.exams = Array.isArray(src.exams) ? src.exams.slice(0, 20) : [];
    state.lastExam = src.lastExam || state.exams[0] || null;
    state.practiceSession = sanitizeSession(src.practiceSession);
    state.examSession = sanitizeSession(src.examSession);
    applySettings();
    saveStateNow();
    render();
  }

  function importProgress() {
    const input = document.createElement('input');
    input.type = 'file';
    input.accept = 'application/json,.json';
    input.style.position = 'fixed';
    input.style.opacity = '0';
    document.body.appendChild(input);
    input.addEventListener('change', () => {
      const file = input.files && input.files[0];
      if (!file) { input.remove(); return; }
      const reader = new FileReader();
      reader.onload = () => {
        try {
          applyImportedState(JSON.parse(String(reader.result || '')));
          toast('Progress imported. Your previous data was replaced.', 'success', 5000);
        } catch (err) {
          toast(`Could not import that file: ${err.message}`, 'error', 6500);
        } finally {
          input.remove();
        }
      };
      reader.onerror = () => { toast('Could not read that file.', 'error'); input.remove(); };
      reader.readAsText(file);
    });
    input.click();
  }

