  function optionText(q, letter) {
    const o = (q.options || []).find((x) => String(x.key) === String(letter));
    return o ? o.text : '';
  }

  function answerShort(q, ans) {
    if (!ans) return 'No key';
    if (ans.letters) return ans.letters.join(', ');
    if (ans.order) return ans.order.join(' → ');
    if (ans.controls) return `${ans.controls.length} selection${ans.controls.length === 1 ? '' : 's'}`;
    return '—';
  }

  function answerText(q, ans) {
    if (!ans) return 'No answer key was supplied for this item.';
    if (ans.letters) {
      return ans.letters.map((l) => `${l}. ${optionText(q, l)}`).join('\n');
    }
    if (ans.order) {
      return ans.order.map((l, i) => `${i + 1}. ${l}. ${optionText(q, l)}`).join('\n');
    }
    if (ans.controls) {
      return ans.controls.map((c) => `${c.label} → ${c.answer}`).join('\n');
    }
    return '—';
  }

  function responseText(q, r) {
    if (!r) return 'No response';
    if (r.letters && r.letters.length) {
      return r.letters.map((l) => `${l}. ${optionText(q, l)}`).join('\n');
    }
    if (r.order && r.order.length) {
      return r.order.map((l, i) => `${i + 1}. ${l}. ${optionText(q, l)}`).join('\n');
    }
    if (r.controls && r.controls.length) {
      return r.controls.map((v, i) => `${(q.controls || [])[i] ? q.controls[i].label : `Control ${i + 1}`} → ${v || '—'}`).join('\n');
    }
    return 'No response';
  }

