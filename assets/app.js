  function startPractice(ids, config = {}) {
    const clean = uniq(ids).filter((id) => byId.has(id));
    if (!clean.length) { toast('No questions matched that scope.', 'warn'); return; }
    let order = clean.slice();
    if (config.order === 'random' || !config.order) order = shuffle(order);
    else if (config.order === 'blueprint') order.sort((a, b) => OBJECTIVE_ORDER.indexOf(byId.get(a)._objective) - OBJECTIVE_ORDER.indexOf(byId.get(b)._objective) || a.localeCompare(b));
    else if (config.order === 'weakest') {
      order.sort((a, b) => {
        const aa = attemptOf(a); const bb = attemptOf(b);
        const aw = aa && aa.lastResult === 'wrong' ? 0 : 1;
        const bw = bb && bb.lastResult === 'wrong' ? 0 : 1;
        return aw - bw;
      });
    }
    const requested = config.count === 'all' ? order.length : Number(config.count) || order.length;
    const take = order.slice(0, Math.min(requested, order.length));
    state.practiceSession = {
      id: `practice-${Date.now()}`,
      createdAt: Date.now(),
      startedAt: Date.now(),
      finishedAt: null,
      ids: take,
      index: 0,
      responses: {},
      revealed: {},
      results: {},
      config: { ...config, count: take.length },
    };
    saveStateNow();
    navigate('#/practice');
    toast(`Practice started · ${plural(take.length, 'question')}`, 'success');
  }

