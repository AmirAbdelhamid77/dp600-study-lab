  function examPool(cfg) {
    let pool = questions.filter((q) => q.answer && q.answerStatus !== 'missing');
    if (!cfg.includeDisputed) pool = pool.filter((q) => q.answerStatus !== 'conflict');
    if (!cfg.includeVisual) pool = pool.filter((q) => !q._visual);
    if (cfg.domain) pool = pool.filter((q) => q._domain === cfg.domain);
    return pool;
  }

  function allocate(total, weights) {
    const entries = Object.entries(weights).map(([d, w]) => ({ d, exact: total * w, n: Math.floor(total * w) }));
    let rem = total - sum(entries.map((e) => e.n));
    const byRemainder = entries.slice().sort((a, b) => (b.exact - b.n) - (a.exact - a.n));
    for (let i = 0; i < rem; i++) byRemainder[i % byRemainder.length].n++;
    return Object.fromEntries(entries.map((e) => [e.d, e.n]));
  }

  function buildExamIds(cfg) {
    const pool = examPool(cfg);
    const total = Math.min(Number(cfg.count) || 50, pool.length);
    if (!total) return { ids: [], pool, total: 0 };
    if (cfg.weighting === 'uniform' || cfg.domain) {
      return { ids: shuffle(pool).slice(0, total).map((q) => q.id), pool, total };
    }
    const alloc = allocate(total, DOMAIN_WEIGHTS);
    const used = new Set();
    const ids = [];
    for (const d of DOMAIN_ORDER) {
      const domainPool = shuffle(pool.filter((q) => q._domain === d));
      const need = alloc[d] || 0;
      for (const q of domainPool.slice(0, need)) { ids.push(q.id); used.add(q.id); }
    }
    if (ids.length < total) {
      for (const q of shuffle(pool)) {
        if (ids.length >= total) break;
        if (!used.has(q.id)) { ids.push(q.id); used.add(q.id); }
      }
    }
    return { ids: shuffle(ids), pool, total };
  }

