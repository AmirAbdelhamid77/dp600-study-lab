  function practicePool(f) {
    return questions.filter((q) => {
      if (f.domain && q._domain !== f.domain) return false;
      if (f.objective && q._objective !== f.objective) return false;
      if (f.pack && q.pack !== f.pack) return false;
      if (f.type && q.type !== f.type) return false;
      if (f.status && q.answerStatus !== f.status) return false;
      if (f.difficulty && String(q.difficulty) !== String(f.difficulty)) return false;
      if (f.attempt === 'unseen' && isAttempted(q.id)) return false;
      if (f.attempt === 'seen' && !isAttempted(q.id)) return false;
      if (f.attempt === 'wrong' && lastResultOf(q.id) !== 'wrong') return false;
      if (f.attempt === 'bookmarked' && !isBookmarked(q.id)) return false;
      if (f.attempt === 'flagged' && !isFlagged(q.id)) return false;
      return true;
    });
  }

