  function responseComplete(q, r) {
    if (!r) return false;
    if (q.type === 'single') return Array.isArray(r.letters) && r.letters.length === 1;
    if (q.type === 'multi') return Array.isArray(r.letters) && r.letters.length >= 1;
    if (q.type === 'sequence') return Array.isArray(r.order) && r.order.length === (q.options || []).length;
    if (q.type === 'controls') {
      const cs = q.controls || [];
      return Array.isArray(r.controls) && r.controls.length === cs.length && r.controls.every((v) => String(v || '').trim() !== '');
    }
    return false;
  }

  function sameSet(a, b) {
    if (!Array.isArray(a) || !Array.isArray(b) || a.length !== b.length) return false;
    const aa = a.map(String).sort();
    const bb = b.map(String).sort();
    return aa.every((v, i) => v === bb[i]);
  }

  function answerMatches(q, r) {
    if (!q.answer || !r) return false;
    if (q.type === 'single' || q.type === 'multi') {
      return sameSet(r.letters || [], q.answer.letters || []);
    }
    if (q.type === 'sequence') {
      const a = r.order || [];
      const b = q.answer.order || [];
      return a.length === b.length && a.every((v, i) => String(v) === String(b[i]));
    }
    if (q.type === 'controls') {
      const expected = q.answer.controls || [];
      const actual = r.controls || [];
      return expected.length === actual.length && expected.every((c, i) => normalizeAnswerText(c.answer) === normalizeAnswerText(actual[i]));
    }
    return false;
  }

  function gradeResponse(q, r) {
    if (!responseComplete(q, r)) return { status: 'incomplete', correct: null };
    if (!q.answer || q.answerStatus === 'missing') return { status: 'ungraded', correct: null };
    if (q.answerStatus === 'conflict') {
      return { status: 'disputed', correct: null, matchesShownKey: answerMatches(q, r) };
    }
    const ok = answerMatches(q, r);
    return { status: ok ? 'correct' : 'wrong', correct: ok };
  }

  function recordAttempt(q, response, result, mode) {
    if (!q || result === 'incomplete') return;
    const a = state.attempts[q.id] || { seen: 0, correct: 0, wrong: 0, disputed: 0, ungraded: 0, history: [] };
    a.seen = (a.seen || 0) + 1;
    if (result === 'correct') a.correct = (a.correct || 0) + 1;
    else if (result === 'wrong') a.wrong = (a.wrong || 0) + 1;
    else if (result === 'disputed') a.disputed = (a.disputed || 0) + 1;
    else if (result === 'ungraded') a.ungraded = (a.ungraded || 0) + 1;
    a.lastAt = Date.now();
    a.lastResult = result;
    a.lastResponse = response || null;
    a.lastMode = mode || 'practice';
    a.history = Array.isArray(a.history) ? a.history : [];
    a.history.push({ at: a.lastAt, result, mode: mode || 'practice' });
    if (a.history.length > 20) a.history.shift();
    state.attempts[q.id] = a;

    const key = dateKey();
    const day = state.activity[key] || { attempts: 0, correct: 0 };
    day.attempts = (day.attempts || 0) + 1;
    if (result === 'correct') day.correct = (day.correct || 0) + 1;
    state.activity[key] = day;
    saveState();
  }

