  function startDiagnostic() {
    const eligible = questions.filter((q) => q._gradeable && !q._visual);
    const alloc = { '1': 5, '2': 10, '3': 5 };
    const picked = [];
    const used = new Set();
    for (const d of DOMAIN_ORDER) {
      const pool = shuffle(eligible.filter((q) => q._domain === d && !isAttempted(q.id)));
      for (const q of pool.slice(0, alloc[d])) { picked.push(q.id); used.add(q.id); }
    }
    if (picked.length < 20) {
      for (const q of shuffle(eligible)) {
        if (picked.length >= 20) break;
        if (!used.has(q.id)) { picked.push(q.id); used.add(q.id); }
      }
    }
    if (!picked.length) { toast('No scoreable questions are available for a diagnostic.', 'warn'); return; }
    startPractice(picked, { count: picked.length, order: 'random', source: 'diagnostic' });
    toast('Diagnostic started · blueprint-weighted, 20 questions.', 'success', 4200);
  }

